#!/usr/bin/env python3
"""AST census: which engine module does each test_*.py actually import?"""
from __future__ import annotations
import ast, argparse, sys
from pathlib import Path

STAGE = Path(__file__).resolve().parent.parent
ENGINE_MODULES = ('HL_Live_Copy_Service_Core', 'HL_Live_Copy_Service', 'exchange_truth')


def imports_of(path):
    try:
        tree = ast.parse(path.read_text(encoding='utf-8-sig', errors='replace'))
    except SyntaxError as exc:
        return {'<SYNTAX_ERROR:%s>' % exc.lineno}
    names = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                names.add(alias.name.split('.')[0])
        elif isinstance(node, ast.ImportFrom):
            if node.module and not node.level:
                names.add(node.module.split('.')[0])
    return names


def census(stage):
    rows = []
    for path in sorted(stage.glob('test_*.py')):
        names = imports_of(path)
        rows.append((path.name, {m: (m in names) for m in ENGINE_MODULES}))
    return rows


def render(rows):
    out = ['# Test import census \u2014 which engine module each test actually loads', '',
           'Generated by `_archive/hl_stage2/tools/test_import_census.py` (AST import scan, not grep).', '',
           '| test file | Core | legacy HL_Live_Copy_Service | exchange_truth | ships? |',
           '| --- | --- | --- | --- | --- |']
    blind = []
    for name, hit in rows:
        cells = [('YES' if hit[m] else '-') for m in ENGINE_MODULES]
        ships = any(hit.values())
        out.append('| `%s` | %s | %s | %s | %s |' % (name, cells[0], cells[1], cells[2],
                                                   'yes' if ships else '**NO \u2014 imports nothing that ships**'))
        if not ships:
            blind.append(name)
    out += ['', '## Verdict', '']
    core = [n for n, hit in rows if hit['HL_Live_Copy_Service_Core']]
    out.append(('Core-targeted suites present: ' + ', '.join('`%s`' % n for n in core)) if core
               else '**No test imports `HL_Live_Copy_Service_Core`.**')
    if blind:
        out += ['', 'Tests that import nothing that ships: ' + ', '.join('`%s`' % n for n in blind)]
    return '\n'.join(out) + '\n'


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=str(STAGE / 'evidence' / 'TEST_IMPORT_CENSUS.md'))
    args = ap.parse_args(argv)
    rows = census(STAGE)
    text = render(rows)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding='utf-8', newline='\n')
    print(text)
    print('CENSUS::WROTE %s (%d test files)' % (out, len(rows)))
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
