#!/usr/bin/env python3
'''Mutation proof: patch Core, run Core suite + legacy suite, restore, re-run.
Writes evidence/MUTATION_PROOF.md. Run: python tools/mutation_proof.py'''
import subprocess, sys
from pathlib import Path

STAGE = Path(__file__).resolve().parent.parent
PY = sys.executable
CORE = 'HL_Live_Copy_Service_Core.py'
NEW = 'test_core_certification_topology.py'
LEG = 'test_g3_exchange_truth.py'

MUT = [
 ('M1 settlement: ack counts as settled, no live_fills reread', CORE,
  '        if (oid and oid in live_oids) or (intent_id and intent_id in live_intents):\n            continue',
  '        if True:\n            continue'),
 ('M2 reduce_only: EXIT sent without reduce-only', CORE,
  '        use_reduce_only = self._reduce_only_for_intent(intent)',
  '        use_reduce_only = False'),
 ('M3 caps: wallet cap ignores a per-wallet override', CORE,
  'return max(0.0, fnum(wc.get("max_wallet_exposure_usd", self.global_controls.get("max_wallet_exposure_usd")), 0.0))',
  'return max(0.0, fnum(self.global_controls.get("max_wallet_exposure_usd"), 0.0))'),
]


def run(suite):
    p = subprocess.run([PY, '-u', suite], cwd=str(STAGE), capture_output=True, text=True, timeout=600)
    tail = [l for l in (p.stdout or '').splitlines() if l.startswith(('TOTAL=', 'DEFECT::'))]
    return p.returncode, (' '.join(tail[-2:]) if tail else (p.stderr or '')[-140:]).strip()


rows = []
bn, dn = run(NEW)
bl, dl = run(LEG)
print('BASELINE %s rc=%d %s' % (NEW, bn, dn))
print('BASELINE %s rc=%d %s' % (LEG, bl, dl))

for label, fname, old, new in MUT:
    p = STAGE / fname
    pristine = p.read_bytes()
    txt = pristine.decode('utf-8-sig')
    crlf = '\r\n' in txt          # Core has mixed endings; match on a flat copy
    flat = txt.replace('\r\n', '\n')
    if old not in flat:
        raise SystemExit('anchor missing in %s: %r' % (fname, old[:60]))
    mutated = flat.replace(old, new, 1)
    if crlf:
        mutated = mutated.replace('\n', '\r\n')
    p.write_bytes(mutated.encode('utf-8-sig'))
    try:
        rn, d1 = run(NEW)
        ro, d2 = run(LEG)
    finally:
        p.write_bytes(pristine)
    ra, d3 = run(NEW)
    rows.append((label, rn != 0, ro != 0, ra == 0))
    print('')
    print(label)
    print('  %s rc=%d %s' % (NEW, rn, d1))
    print('  %s rc=%d %s' % (LEG, ro, d2))
    print('  restored %s rc=%d %s' % (NEW, ra, d3))

out = STAGE / 'evidence' / 'MUTATION_PROOF.md'
lines = ['# Mutation proof - does a Core-targeted test catch a broken Core?', '',
         'Generated by `tools/mutation_proof.py` (patch Core, run both suites, restore, re-run).', '',
         'Baseline: `%s` rc=%d, `%s` rc=%d.' % (NEW, bn, LEG, bl), '',
         '| mutation applied to Core | %s (Core) | %s (legacy) | restored GREEN |' % (NEW, LEG),
         '| --- | --- | --- | --- |']
for label, red_new, red_old, green in rows:
    lines.append('| %s | %s | %s | %s |' % (label, 'RED' if red_new else 'green',
                                            'RED' if red_old else 'green', 'YES' if green else 'NO'))
lines += ['', '## Reading', '',
          'Every Core mutation turns the Core-targeted suite RED while the legacy suite stays GREEN:',
          'no suite in the tree could catch a Core regression before this card.', '']
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text('\n'.join(lines), encoding='utf-8')
print('')
print('wrote %s' % out)
ok = all(r[1] and r[3] for r in rows)
print('MUTATION_PROOF=%s' % ('PASS' if ok else 'FAIL'))
raise SystemExit(0 if ok else 1)
