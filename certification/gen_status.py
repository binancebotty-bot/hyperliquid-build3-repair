#!/usr/bin/env python3
"""Build the run-by-run certification status table from certification_matrix.json and run_results.json.

Writes RUN_STATUS.md (summary plus every requirement with a recorded result) and run_status.csv (all requirements).
A requirement's current status comes from the matrix `result` field (the register of record).
run_results.json provides the run history table and per-requirement history.
A requirement with proof_network MAINNET (price quality, slippage, markets absent on testnet) can only PASS from a run
whose follower_network is mainnet; a testnet PASS on it is shown as NEEDS_MAINNET.
"""
import csv, json, subprocess, sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Read matrix from git ref if --ref is provided, else from working tree
git_ref = None
if "--ref" in sys.argv:
    git_ref = sys.argv[sys.argv.index("--ref") + 1]
    raw = subprocess.run(["git", "show", f"{git_ref}:certification/certification_matrix.json"],
                        capture_output=True)
    if raw.returncode != 0:
        raise SystemExit(f"git show {git_ref}:certification/certification_matrix.json failed: {raw.stderr.decode().strip()}")
    matrix = json.loads(raw.stdout.decode())
    _sha = subprocess.run(["git", "rev-parse", git_ref], capture_output=True, text=True).stdout.strip()
    matrix_source = f"{git_ref}@{_sha}"
else:
    matrix = json.loads((HERE / "certification_matrix.json").read_text())
    matrix_source = "working tree"

runs = json.loads((HERE / "run_results.json").read_text())["runs"]
recs = {r["id"]: r for r in matrix["records"]}

# Skip run_results entries for requirements not in the matrix
_skipped = []
for run in runs:
    _skipped.extend(r["id"] for r in run["results"] if r["id"] not in recs)
    run["results"] = [r for r in run["results"] if r["id"] in recs]

# Build history from run_results.json
hist = {}
for run in runs:
    for res in run["results"]:
        if res["id"] not in recs:
            raise SystemExit(f"{run['run']}: unknown requirement {res['id']}")
        if run.get("follower_network") not in ("testnet", "mainnet"):
            raise SystemExit(f"{run['run']}: follower_network must be testnet or mainnet")
        if res["result"] not in ("PASS", "FAIL", "BLOCKED"):
            raise SystemExit(f"{run['run']}: bad result {res['result']} for {res['id']}")
        hist.setdefault(res["id"], []).append((run, res))

rows = []
for rid, r in recs.items():
    # Primary status from matrix result (the register of record)
    status = r.get("result", "NOT_TESTED")
    # NEEDS_MAINNET logic: if matrix says PASS but proof_network=MAINNET, check latest run's follower_network
    if status == "PASS" and r.get("proof_network") == "MAINNET":
        h = hist.get(rid, [])
        if h:
            run, _ = h[-1]
            if run["follower_network"] != "mainnet":
                status = "NEEDS_MAINNET"
    
    # Evidence from matrix
    evidence = r.get("evidence_ref", "")
    # Last run/commit from history if available, else from matrix
    h = hist.get(rid, [])
    if h:
        run, res = h[-1]
        last_run = run["run"]
        commit = run["commit"]
        history = " ; ".join(f"{x['run']}@{x['commit']}({x['follower_network']}):{y['result']}" for x, y in h)
    else:
        last_run = ""
        commit = r.get("tested_commit", "")
        history = ""
    
    rows.append(dict(id=rid, area=r["area"], feature=r["feature"], applicability=r["applicability"],
                     proof_network=r.get("proof_network", "TESTNET"), status=status,
                     last_run=last_run, commit=commit, evidence=evidence, history=history))

with open(HERE / "run_status.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)

live = [x for x in rows if x["applicability"] != "SUPERSEDED"]
c = Counter(x["status"] for x in live)

out = ["# Certification run status", "",
       "Generated by `gen_status.py` from `certification_matrix.json` and `run_results.json`. Do not edit by hand: add a run to `run_results.json` and regenerate.", "",
       f"Input matrix: `{matrix_source}`", "",
       "Note: A PASS-row evidence audit has demoted a substantial portion of the PASS rows; the PASS count below reflects the matrix state, not a fully verified position.", "",
       f"Skipped {len(_skipped)} run_results entries for requirements not in the matrix: {', '.join(_skipped)}" if _skipped else "", "",
       f"**{len(live)} live requirements:** {c['PASS']} PASS, {c['FAIL']} FAIL, {c['BLOCKED']} BLOCKED, {c['NEEDS_MAINNET']} NEEDS_MAINNET, {c['NOT_TESTED']} NOT_TESTED. "
       "A PASS here is a run result on that run's commit; certification still needs every applicable requirement to PASS on one final commit (contract §3.3).", "",
       f"**Testnet proves latency, accounting, wiring and controls.** Most testnet books are illiquid, so slippage and price quality cannot be judged there (owner, 2026-10-09). "
       f"{sum(1 for x in live if x['proof_network'] == 'MAINNET')} requirements are marked `proof_network = MAINNET` and reach PASS only from a run whose follower is on mainnet; a testnet PASS on them shows as NEEDS_MAINNET. They are listed at the end.", "",
       "## Runs", "", "| Run | Date | Commit | Network | Follower | Report | Summary |", "|---|---|---|---|---|---|---|"]
for run in runs:
    out.append(f"| {run['run']} | {run['date']} | `{run['commit']}` | {run['network']} | {run['follower_network']} | {run['report']} | {run['summary']} |")
out += ["", "## By area", "", "| Area | PASS | FAIL | BLOCKED | NEEDS_MAINNET | NOT_TESTED |", "|---|---|---|---|---|---|"]
for area in sorted({x["area"] for x in live}):
    ac = Counter(x["status"] for x in live if x["area"] == area)
    out.append(f"| {area} | {ac['PASS']} | {ac['FAIL']} | {ac['BLOCKED']} | {ac['NEEDS_MAINNET']} | {ac['NOT_TESTED']} |")
out += ["", "## Requirements with a recorded result", "", "| ID | Feature | Status | Run | Commit | Evidence | History |", "|---|---|---|---|---|---|---|"]
for x in sorted((x for x in rows if x["status"] != "NOT_TESTED"), key=lambda x: ({"FAIL": 0, "BLOCKED": 1, "NEEDS_MAINNET": 2, "PASS": 3}[x["status"]], x["id"])):
    out.append(f"| {x['id']} | {x['feature']} | **{x['status']}** | {x['last_run']} | `{x['commit']}` | {x['evidence'].replace('|', '/')} | {x['history']} |")
out += ["", "Every other requirement is NOT_TESTED; see `run_status.csv` for the full list.", "",
        "## Requirements that need mainnet proof", "", "| ID | Feature | Status | Why |", "|---|---|---|---|"]
for x in (x for x in rows if x["proof_network"] == "MAINNET" and x["applicability"] != "SUPERSEDED"):
    why = recs[x["id"]]["notes"].split("Mainnet proof required: ", 1)[-1].rstrip(".")
    out.append(f"| {x['id']} | {x['feature']} | {x['status']} | {why.replace('|', '/')} |")
out.append("")
(HERE / "RUN_STATUS.md").write_text("\n".join(out))
print(len(rows), dict(c))
