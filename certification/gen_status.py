#!/usr/bin/env python3
"""Build the run-by-run certification status table from certification_matrix.json and run_results.json.

Writes RUN_STATUS.md (summary plus every requirement with a recorded result) and run_status.csv (all requirements).
A requirement's current status is its result in the latest run that tested it; earlier runs stay in the history.
"""
import csv, json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
matrix = json.loads((HERE / "certification_matrix.json").read_text())
runs = json.loads((HERE / "run_results.json").read_text())["runs"]
recs = {r["id"]: r for r in matrix["records"]}

hist = {}
for run in runs:
    for res in run["results"]:
        if res["id"] not in recs:
            raise SystemExit(f"{run['run']}: unknown requirement {res['id']}")
        if res["result"] not in ("PASS", "FAIL", "BLOCKED"):
            raise SystemExit(f"{run['run']}: bad result {res['result']} for {res['id']}")
        hist.setdefault(res["id"], []).append((run, res))

rows = []
for rid, r in recs.items():
    h = hist.get(rid, [])
    run, res = h[-1] if h else (None, None)
    rows.append(dict(id=rid, area=r["area"], feature=r["feature"], applicability=r["applicability"],
                     status=res["result"] if res else "NOT_TESTED",
                     last_run=run["run"] if run else "", commit=run["commit"] if run else "",
                     evidence=res["evidence"] if res else "",
                     history=" ; ".join(f"{x['run']}@{x['commit']}:{y['result']}" for x, y in h)))

with open(HERE / "run_status.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)

live = [x for x in rows if x["applicability"] != "SUPERSEDED"]
c = Counter(x["status"] for x in live)
out = ["# Certification run status", "",
       "Generated by `gen_status.py` from `certification_matrix.json` and `run_results.json`. Do not edit by hand: add a run to `run_results.json` and regenerate.", "",
       f"**{len(live)} live requirements:** {c['PASS']} PASS, {c['FAIL']} FAIL, {c['BLOCKED']} BLOCKED, {c['NOT_TESTED']} NOT_TESTED. "
       "A PASS here is a run result on that run's commit; certification still needs every applicable requirement to PASS on one final commit (contract §3.3).", "",
       "## Runs", "", "| Run | Date | Commit | Network | Report | Summary |", "|---|---|---|---|---|---|"]
for run in runs:
    out.append(f"| {run['run']} | {run['date']} | `{run['commit']}` | {run['network']} | {run['report']} | {run['summary']} |")
out += ["", "## By area", "", "| Area | PASS | FAIL | BLOCKED | NOT_TESTED |", "|---|---|---|---|---|"]
for area in sorted({x["area"] for x in live}):
    ac = Counter(x["status"] for x in live if x["area"] == area)
    out.append(f"| {area} | {ac['PASS']} | {ac['FAIL']} | {ac['BLOCKED']} | {ac['NOT_TESTED']} |")
out += ["", "## Requirements with a recorded result", "", "| ID | Feature | Status | Run | Commit | Evidence | History |", "|---|---|---|---|---|---|---|"]
for x in sorted((x for x in rows if x["status"] != "NOT_TESTED"), key=lambda x: ({"FAIL": 0, "BLOCKED": 1, "PASS": 2}[x["status"]], x["id"])):
    out.append(f"| {x['id']} | {x['feature']} | **{x['status']}** | {x['last_run']} | `{x['commit']}` | {x['evidence'].replace('|', '/')} | {x['history']} |")
out += ["", "Every other requirement is NOT_TESTED; see `run_status.csv` for the full list.", ""]
(HERE / "RUN_STATUS.md").write_text("\n".join(out))
print(len(rows), dict(c))
