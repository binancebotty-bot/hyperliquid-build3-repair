def main():
    doc = json.loads(MATRIX.read_text(encoding="utf-8"))
    recs = doc["records"]
    by_id = {r["id"]: r for r in recs}
    applied, missing = [], []
    for rid, (result, ref, at, note) in sorted(V.items()):
        rec = by_id.get(rid)
        if rec is None:
            missing.append(rid)
            continue
        rec["result"] = result
        rec["evidence_ref"] = ref
        rec["tested_commit"] = COMMIT
        rec["tested_at_utc"] = at
        prev = rec.get("notes") or ""
        rec["notes"] = (prev + " | " if prev else "") + note
        applied.append((rid, result))
    MATRIX.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print("applied:", len(applied))
    for rid, res in applied:
        print("  %-12s %s" % (rid, res))
    if missing:
        print("MISSING (not written):", missing)
    print("tally:", dict(Counter(r["result"] for r in recs)))


if __name__ == "__main__":
    main()
